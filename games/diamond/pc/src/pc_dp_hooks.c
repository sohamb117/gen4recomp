/* pc_main.c: PC_SELFTEST. The suites are Platinum's host replacements;
 * say so rather than report a pass nothing ran. */
int pc_selftest_run(FILE *out)
{
    if (out == NULL) {
        out = stderr;
    }
    fprintf(out, "pc-selftest: the self-test suites test Platinum's host "
                 "replacements and are not built for Diamond/Pearl\n");
    return 0;
}

