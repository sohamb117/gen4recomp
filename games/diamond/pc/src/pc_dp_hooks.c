#include <stdlib.h>
/*
 * The calls the shared host layer makes into Platinum-only host files,
 * answered by a Diamond/Pearl build that does not compile those files.
 *
 * pc/mk/host.mk leaves out games/platinum/pc/src's game-specific half: the
 * labs (pc_lab, pc_sprite_lab, pc_text_lab, pc_audio_lab) and
 * pc_bgm_mute.c drive Platinum's own C (Bag_*, SoundSystem_*, ...);
 * pc_modfs.c serves Platinum mods by replacing FS_OpenFile/FS_ReadFile and
 * reading Platinum NARC layouts; pc_probe2d.c reads Platinum's gSystem;
 * pc_selftest.c's suites test pc_dgt.c and pc_crypto_rc4.c, which replace
 * Platinum-SDK code D runs as its own recompiled DGT; mods_manifest.c is
 * generated by Platinum's makefile. The machine model calls them
 * unconditionally (each decides from an environment variable that it has
 * nothing to do), so the call sites stay and these are the answers, the
 * way games/platinum/3ds/src/3ds_hooks.c answers the same calls on the
 * 3DS. Strong, not weak: bringing one of the files back to D is a
 * multiple-definition error and therefore a decision.
 *
 * The signatures are the call sites' (pc_video.c, pc_os_lite.c, pc_main.c,
 * pc_dma.c, pc_mi.c), which declare them locally.
 */
#include <stdint.h>
#include <stdio.h>

/* pc_video.c's per-frame lab hooks. */
/* pc_lab_frame is also D's per-frame diagnostic point: PC_DP_HEAPCHECK=1
 * validates the game's heaps every frame, =2 on every Heap_Alloc/Heap_Free
 * as well (pc/patches/arm9/src/heap.c.patch). */
extern void pc_dp_heap_check(const char *where);
extern int pc_dp_heapcheck_level;
extern unsigned long long pc_dp_heapcheck_frame;
void pc_lab_frame(unsigned long long frame)
{
    static int init;
    if (!init) {
        const char *e = getenv("PC_DP_HEAPCHECK");
        pc_dp_heapcheck_level = e ? atoi(e) : 0;
        init = 1;
    }
    pc_dp_heapcheck_frame = frame;
    if (pc_dp_heapcheck_level >= 1) pc_dp_heap_check("frame");
}
