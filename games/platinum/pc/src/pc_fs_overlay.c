/*
 * FS_StartOverlay, for a port whose overlays never leave memory.
 *
 * On hardware, loading an overlay reads its image out of the ROM into RAM and
 * then FS_StartOverlay runs the overlay's static initialisers, a list of
 * function addresses the SDK linker assigned inside the overlay's own text.
 * The compiled SDK version of that walk is faithful, and here faithful is
 * fatal: the overlay table comes from the real ROM, so the entries are DS
 * addresses and calling one jumps into guest RAM.
 *
 * That is not hypothetical. The first battle anyone reached on this port died
 * at an address the ROM link's own map names as battle_main.c's
 * NitroStaticInit with the Thumb bit set. Every overlay loaded before that
 * point has an empty list, which is why days of intro, overworld and menus
 * never tripped it.
 *
 * The correct model for C++-style statics is still to call nothing: those are
 * host globals the loader already ran. NitroStaticInit is different; it is a
 * regular function the overlay loader is supposed to call, and gcc never does.
 * Poketch apps use it to hand New and Exit to the system that just created
 * itself, and skipping it leaves currAppInit as stack garbage.
 *
 * pc/include/nitro/sinit.h records each unit's NitroStaticInit at process
 * start. This walks the ones whose source file belongs to the overlay that
 * just loaded. Overlays that register none still see an empty walk.
 *
 * FS_EndOverlay stays the SDK's: its destructor walk filters by the overlay's
 * guest address range, and no host destructor registers an address there.
 *
 * Reload resets host statics. On hardware the ROM copy is the reset; here the
 * statics are host globals, so the first StartOverlay snapshots the
 * CRT-initialised bytes and every later one copies that snapshot back. The
 * name list is generated from nm over each overlay's objects, and the
 * addresses come from the binary's own .symtab at runtime, because a generated
 * pointer table would move the very addresses it named. A host with no
 * .symtab (3DS, wasm) carries them in a table of the generator's, patched
 * into the finished image after the link; pc_sym.h answers the same way.
 */
