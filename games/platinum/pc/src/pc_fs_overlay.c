#define PC_SINIT_MAX 128

struct pc_sinit_entry {
    const char *file;
    void (*fn)(void);
};

static struct pc_sinit_entry sSinit[PC_SINIT_MAX];
static int sSinitN;

void pc_sinit_record(const char *file, void (*fn)(void))
{
    if (sSinitN >= PC_SINIT_MAX) {
        fprintf(stderr, "pc_sinit: more than %d NitroStaticInit TUs\n",
                PC_SINIT_MAX);
        exit(2);
    }
    sSinit[sSinitN].file = file;
    sSinit[sSinitN].fn = fn;
    sSinitN++;
}

